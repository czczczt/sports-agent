"""Детерминированная инициализация таблиц спортсменов (athlete, result_athlete, athlete_assessment_cache).

Поддерживает работу с PostgreSQL (по умолчанию через DATABASE_URL) и обратную совместимость с SQLite.
НЕ МЕНЯЕТ существующие таблицы (source, competition, race, result, issue, known_exception).
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import os
import re
import sys
import time
from typing import Any

from app.config import DATABASE_URL, normalize_postgres_url


DUMMY_CLUBS_EXACT = {"нет", "лично", "индивидуально", "-", "—", "none", "null", "self", "individual", ""}
DUMMY_CLUBS_SUBSTR = ("нет клуба", "no club", "без клуба")


def is_dummy_club(club: str | None) -> bool:
    if not club:
        return True
    s = club.strip().lower().replace("ё", "е")
    if s in DUMMY_CLUBS_EXACT:
        return True
    if any(k in s for k in DUMMY_CLUBS_SUBSTR):
        return True
    return False


def norm_name(name: str | None) -> str:
    if not name:
        return ""
    s = name.lower().replace("ё", "е")
    tokens = sorted(re.findall(r"[a-zа-я0-9]+", s))
    return " ".join(tokens)


def setup_schema(conn: Any, is_postgres: bool = True) -> None:
    cur = conn.cursor()
    if is_postgres:
        cur.execute("""
        CREATE TABLE IF NOT EXISTS athlete (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            display_name text NOT NULL,
            name_key text NOT NULL,
            gender text,
            birth_year integer,
            city text,
            region text,
            club text,
            starts_count integer DEFAULT 0,
            results_count integer DEFAULT 0,
            created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
            is_hidden boolean DEFAULT false,
            employee_status text DEFAULT 'unknown'
        );
        CREATE INDEX IF NOT EXISTS ix_athlete_name_key ON athlete(name_key);
        CREATE INDEX IF NOT EXISTS ix_athlete_birth_year ON athlete(birth_year);

        CREATE TABLE IF NOT EXISTS result_athlete (
            result_id integer PRIMARY KEY REFERENCES result(id) ON DELETE CASCADE,
            athlete_id integer NOT NULL REFERENCES athlete(id) ON DELETE CASCADE
        );
        CREATE INDEX IF NOT EXISTS ix_result_athlete_athlete ON result_athlete(athlete_id);

        CREATE TABLE IF NOT EXISTS athlete_assessment_cache (
            athlete_id integer PRIMARY KEY REFERENCES athlete(id) ON DELETE CASCADE,
            assessment_text text NOT NULL,
            metrics_json text NOT NULL,
            model text NOT NULL,
            created_at timestamptz DEFAULT CURRENT_TIMESTAMP
        );
        """)
    else:
        cur.executescript("""
        CREATE TABLE IF NOT EXISTS athlete (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            display_name TEXT NOT NULL,
            name_key TEXT NOT NULL,
            gender TEXT,
            birth_year INTEGER,
            city TEXT,
            region TEXT,
            club TEXT,
            starts_count INTEGER DEFAULT 0,
            results_count INTEGER DEFAULT 0,
            created_at TEXT DEFAULT CURRENT_TIMESTAMP
        );
        CREATE INDEX IF NOT EXISTS ix_athlete_name_key ON athlete(name_key);
        CREATE INDEX IF NOT EXISTS ix_athlete_birth_year ON athlete(birth_year);

        CREATE TABLE IF NOT EXISTS result_athlete (
            result_id INTEGER PRIMARY KEY,
            athlete_id INTEGER NOT NULL REFERENCES athlete(id)
        );
        CREATE INDEX IF NOT EXISTS ix_result_athlete_athlete ON result_athlete(athlete_id);

        CREATE TABLE IF NOT EXISTS athlete_assessment_cache (
            athlete_id INTEGER PRIMARY KEY REFERENCES athlete(id),
            assessment_text TEXT NOT NULL,
            metrics_json TEXT NOT NULL,
            model TEXT NOT NULL,
            created_at TEXT DEFAULT CURRENT_TIMESTAMP
        );
        """)
    conn.commit()


def populate_athletes(db_target: str | None = None) -> dict[str, int]:
    target = db_target or os.environ.get("DATABASE_URL") or DATABASE_URL
    is_sqlite = str(target).endswith(".db") or str(target).endswith(".sqlite") or "sqlite" in str(target)

    if is_sqlite:
        import sqlite3
        conn = sqlite3.connect(target)
        is_postgres = False
    else:
        import psycopg
        pg_url = normalize_postgres_url(target)
        conn = psycopg.connect(pg_url)
        is_postgres = True

    cur = conn.cursor()
    setup_schema(conn, is_postgres=is_postgres)

    # Проверяем, заполнена ли уже таблица athlete
    cur.execute("SELECT count(*) FROM athlete")
    count_row = cur.fetchone()
    count = count_row[0] if count_row else 0
    if count > 0:
        print(f"Таблица athlete уже содержит {count} записей. Пропуск генерации.")
        conn.close()
        return {"athletes": count, "links": 0, "skipped": True}

    print("Начало группировки результатов в спортсменов...")
    t0 = time.time()

    query_pg = """
        SELECT r.id, r.full_name_raw, r.gender, r.birth_year, r.age,
               COALESCE(c.date_begin::text, '')::text AS date_begin,
               r.city, r.region, r.club_raw, r.status, r.duplicate_of
        FROM result r
        JOIN race ra ON ra.id = r.race_id
        JOIN competition c ON c.id = ra.competition_id
    """

    query_sqlite = """
        SELECT r.id, r.full_name_raw, r.gender, r.birth_year, r.age,
               e.date_begin, r.city, r.region, r.club_raw, r.status, r.duplicate_of
        FROM result r
        JOIN race ra ON ra.id = r.race_id
        JOIN event e ON e.id = ra.event_id
    """

    query = query_pg if is_postgres else query_sqlite
    try:
        cur.execute(query)
        rows = cur.fetchall()
    except Exception:
        if not is_postgres:
            # Fallback for sqlite if table is named competition
            cur.execute("""
                SELECT r.id, r.full_name_raw, r.gender, r.birth_year, r.age,
                       c.date_begin, r.city, r.region, r.club_raw, r.status, r.duplicate_of
                FROM result r
                JOIN race ra ON ra.id = r.race_id
                JOIN competition c ON c.id = ra.competition_id
            """)
            rows = cur.fetchall()
        else:
            raise

    print(f"Загружено {len(rows)} строк за {time.time() - t0:.2f} сек.")

    groups: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for r in rows:
        rid, name_raw, gender, byear, age, dbegin, city, region, club, status, dup = r
        if not name_raw:
            continue
        nkey = norm_name(name_raw)
        cyear = byear
        if cyear is None and age is not None and dbegin:
            try:
                cyear = int(str(dbegin)[:4]) - age
            except Exception:
                pass
        groups[(nkey, gender or "")].append({
            "rid": rid, "name_raw": name_raw, "year": cyear,
            "city": city, "region": region, "club": club,
            "status": status, "dup": dup
        })

    athletes_to_insert = []
    links_to_insert = []
    athlete_id = 0

    for (nkey, gender), items in groups.items():
        with_year = [it for it in items if it["year"] is not None]
        no_year = [it for it in items if it["year"] is None]

        clusters = []
        if with_year:
            with_year.sort(key=lambda x: x["year"])
            current_cluster = [with_year[0]]
            for it in with_year[1:]:
                # Допуск в 1 год между соседними результатами внутри одного человека
                if it["year"] - current_cluster[-1]["year"] <= 1:
                    current_cluster.append(it)
                else:
                    clusters.append(current_cluster)
                    current_cluster = [it]
            clusters.append(current_cluster)

        if not clusters:
            if no_year:
                clusters.append(no_year)
        else:
            if len(clusters) == 1:
                clusters[0].extend(no_year)
            else:
                if no_year:
                    clusters.append(no_year)

        for cl in clusters:
            athlete_id += 1
            names = [x["name_raw"] for x in cl if x["name_raw"]]
            disp_name = Counter(names).most_common(1)[0][0] if names else nkey
            years = [x["year"] for x in cl if x["year"] is not None]
            rep_year = Counter(years).most_common(1)[0][0] if years else None
            cities = [x["city"] for x in cl if x["city"]]
            rep_city = Counter(cities).most_common(1)[0][0] if cities else None
            regions = [x["region"] for x in cl if x["region"]]
            rep_region = Counter(regions).most_common(1)[0][0] if regions else None
            clubs = [x["club"] for x in cl if x["club"] and not is_dummy_club(x["club"])]
            rep_club = Counter(clubs).most_common(1)[0][0] if clubs else None

            # Завершенные старты без дублей
            fin_starts = sum(1 for x in cl if x["status"] == "FIN" and x["dup"] is None)
            total_results = len(cl)

            athletes_to_insert.append((
                athlete_id, disp_name, nkey, gender if gender else None,
                rep_year, rep_city, rep_region, rep_club, fin_starts, total_results
            ))
            for x in cl:
                links_to_insert.append((x["rid"], athlete_id))

    print(f"Сформировано {len(athletes_to_insert)} спортсменов. Запись в БД...")
    placeholder = "%s" if is_postgres else "?"
    conflict_clause = (
        "ON CONFLICT (id) DO UPDATE SET display_name = EXCLUDED.display_name, "
        "starts_count = EXCLUDED.starts_count, results_count = EXCLUDED.results_count"
        if is_postgres else ""
    )

    cur.executemany(f"""
        INSERT INTO athlete (id, display_name, name_key, gender, birth_year, city, region, club, starts_count, results_count)
        VALUES ({', '.join([placeholder] * 10)})
        {conflict_clause}
    """, athletes_to_insert)

    link_conflict = (
        "ON CONFLICT (result_id) DO UPDATE SET athlete_id = EXCLUDED.athlete_id"
        if is_postgres else ""
    )
    cur.executemany(f"""
        INSERT INTO result_athlete (result_id, athlete_id)
        VALUES ({placeholder}, {placeholder})
        {link_conflict}
    """, links_to_insert)

    conn.commit()
    conn.close()
    print(f"Успешно сохранено: {len(athletes_to_insert)} спортсменов, {len(links_to_insert)} связей.")
    return {"athletes": len(athletes_to_insert), "links": len(links_to_insert), "skipped": False}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Deterministic athlete population for PostgreSQL/SQLite")
    parser.add_argument("--db", default=None, help="Database URL or SQLite path")
    args = parser.parse_args()
    populate_athletes(args.db)
