CREATE TABLE IF NOT EXISTS revoked_token (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash varchar(64) UNIQUE NOT NULL,
    revoked_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_revoked_token_hash ON revoked_token(token_hash);
CREATE INDEX IF NOT EXISTS idx_revoked_token_expires ON revoked_token(expires_at);

CREATE TABLE IF NOT EXISTS password_reset_token (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    token_hash varchar(64) UNIQUE NOT NULL,
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pwd_reset_user ON password_reset_token(user_id);
CREATE INDEX IF NOT EXISTS idx_pwd_reset_hash ON password_reset_token(token_hash);
