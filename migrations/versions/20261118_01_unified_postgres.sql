CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE IF NOT EXISTS source (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text UNIQUE NOT NULL,
    base_url      text NOT NULL,
    platform      text NOT NULL,
    parse_method  text,
    sport_types   text DEFAULT 'run',
    priority      integer DEFAULT 1,
    enabled       boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS competition (
    id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id                 integer NOT NULL REFERENCES source(id),
    external_id               text NOT NULL,
    code                      text,
    name                      text,
    date_begin                date,
    date_end                  date,
    location                  text,
    address                   text,
    sport_type                text,
    source_url                text,
    canonical_competition_id  integer REFERENCES competition(id) ON DELETE SET NULL,
    fetched_at                timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_id, external_id)
);
CREATE INDEX IF NOT EXISTS competition_date ON competition(date_begin);
CREATE TABLE IF NOT EXISTS race (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id     integer NOT NULL REFERENCES competition(id),
    external_id        text NOT NULL,
    name               text,
    distance_km_raw    double precision,
    distance_m         integer,
    distance_type      text,
    race_type          text,
    place_by           text,
    timing_type        integer,
    is_final_protocol  boolean,
    total_count        integer,
    UNIQUE (competition_id, external_id)
);



CREATE TABLE IF NOT EXISTS raw (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id       integer NOT NULL REFERENCES source(id),
    competition_id  integer REFERENCES competition(id) ON DELETE SET NULL,
    race_id         integer REFERENCES race(id) ON DELETE SET NULL,
    object_ref      text,
    url             text,
    request_key     text NOT NULL,
    content_hash    text NOT NULL,
    storage_path    text NOT NULL,
    size_bytes      integer,
    http_status     integer,
    parse_method    text,
    fetched_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_id, request_key, content_hash)
);
CREATE INDEX IF NOT EXISTS raw_object_ref ON raw(object_ref);
CREATE TABLE IF NOT EXISTS club (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_raw           text UNIQUE NOT NULL,
    name_normalized    text,
    is_sber            boolean NOT NULL,
    is_sber_confirmed  boolean
);
CREATE TABLE IF NOT EXISTS result (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id                  integer NOT NULL REFERENCES race(id),
    raw_id                   bigint REFERENCES raw(id) ON DELETE SET NULL,
    athlete_id               bigint,
    club_id                  integer REFERENCES club(id),
    external_participant_id  text,
    bib                      text,
    full_name_raw            text,
    gender                   text,
    age                      integer,
    birth_year               integer,
    birth_date               date,
    country                  text,
    region                   text,
    city                     text,
    club_raw                 text,
    club_source              text,
    status                   text,
    position                 integer,
    position_gender          integer,
    age_group                text,
    chip_time_s              double precision,
    gun_time_s               double precision,
    duplicate_of             bigint REFERENCES result(id) ON DELETE SET NULL,
    match_score              real,
    match_method             text
);
CREATE INDEX IF NOT EXISTS result_race ON result(race_id);
CREATE INDEX IF NOT EXISTS result_duplicate_of ON result(duplicate_of);




CREATE TABLE IF NOT EXISTS issue (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id    integer REFERENCES source(id),
    stage        text NOT NULL,
    kind         text NOT NULL,
    object_ref   text,
    fingerprint  text NOT NULL UNIQUE,
    details      text,
    status       text NOT NULL DEFAULT 'new',
    assignee     text,
    journal_ref  text,
    occurrences  integer NOT NULL DEFAULT 1,
    first_seen   timestamptz NOT NULL DEFAULT now(),
    last_seen    timestamptz NOT NULL DEFAULT now(),
    resolved_at  timestamptz
);

CREATE TABLE IF NOT EXISTS known_exception (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source       text,
    kind         text NOT NULL,
    pattern      text NOT NULL,
    reason       text NOT NULL,
    journal_ref  text,
    UNIQUE NULLS NOT DISTINCT (source, kind, pattern)
);

CREATE TABLE IF NOT EXISTS agent_run (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id     integer NOT NULL REFERENCES issue(id),
    model        text,
    tokens_in    integer,
    tokens_out   integer,
    action       text,
    result       text,
    patch        text,
    test_report  text,
    started_at   timestamptz NOT NULL DEFAULT now(),
    finished_at  timestamptz
);

ALTER TABLE race ADD COLUMN IF NOT EXISTS discipline text CHECK (discipline IN ('road','track'));
ALTER TABLE race ADD COLUMN IF NOT EXISTS class_source text NOT NULL DEFAULT 'auto'
    CHECK (class_source IN ('auto','manual'));
ALTER TABLE race ADD COLUMN IF NOT EXISTS distance_class_override text;
ALTER TABLE result ADD COLUMN IF NOT EXISTS distance_km double precision
    CHECK (distance_km > 0 AND distance_km < 'Infinity'::float8);
CREATE TABLE IF NOT EXISTS distance_synonym (
    pattern text PRIMARY KEY CHECK (length(pattern) > 0),
    distance_class text NOT NULL,
    priority integer NOT NULL DEFAULT 100,
    enabled boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS norm (
    year integer NOT NULL CHECK (year BETWEEN 1 AND 9999),
    distance_class text NOT NULL,
    gender text NOT NULL CHECK (gender IN ('M', 'F')),
    value double precision NOT NULL CHECK (value > 0 AND value < 'Infinity'::float8),
    unit text NOT NULL CHECK (unit = CASE WHEN distance_class = '24h' THEN 'km' ELSE 's' END),
    PRIMARY KEY (year, distance_class, gender)
);
CREATE TABLE IF NOT EXISTS score (
    result_id bigint NOT NULL REFERENCES result(id) ON DELETE CASCADE,
    formula_version text NOT NULL,
    points double precision CHECK (points > 0 AND points < 'Infinity'::float8),
    reason text,
    breakdown jsonb NOT NULL,
    PRIMARY KEY (result_id, formula_version),
    CHECK ((points IS NOT NULL AND reason IS NULL) OR (points IS NULL AND reason IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS agent_review (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id      integer NOT NULL REFERENCES issue(id),
    agent_run_id  integer REFERENCES agent_run(id),
    decision      text NOT NULL CHECK (decision IN ('approved', 'rejected')),
    author        text NOT NULL,
    comment       text,
    decided_at    timestamptz NOT NULL DEFAULT now(),
    applied_result text,
    pr_url        text,
    applied_at    timestamptz
);


CREATE TABLE IF NOT EXISTS athlete (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,display_name text NOT NULL,name_key text NOT NULL,
 gender text,birth_year integer,city text,region text,club text,
 starts_count integer NOT NULL DEFAULT 0,results_count integer NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS athlete_birth_year ON athlete(birth_year);
CREATE TABLE IF NOT EXISTS result_athlete (
 result_id bigint PRIMARY KEY REFERENCES result(id) ON DELETE CASCADE,
 athlete_id bigint NOT NULL REFERENCES athlete(id)
);
CREATE INDEX IF NOT EXISTS result_athlete_athlete_idx ON result_athlete(athlete_id);
CREATE TABLE IF NOT EXISTS athlete_assessment_cache (
 athlete_id bigint PRIMARY KEY REFERENCES athlete(id), assessment_text text NOT NULL,
 metrics_json text NOT NULL,model text NOT NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE migration_import(source_hash text PRIMARY KEY,report jsonb NOT NULL,imported_at timestamptz NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS rating_norm (
    year INTEGER NOT NULL,
    distance_class TEXT NOT NULL,
    gender TEXT NOT NULL CHECK (gender IN ('M', 'F')),
    value DOUBLE PRECISION NOT NULL CHECK (value > 0),
    unit TEXT NOT NULL CHECK (unit IN ('s', 'km')),
    PRIMARY KEY (year, distance_class, gender)
);
CREATE TABLE IF NOT EXISTS rating_score (
    result_id INTEGER NOT NULL REFERENCES result(id) ON DELETE CASCADE,
    formula_version TEXT NOT NULL,
    points DOUBLE PRECISION,
    reason TEXT,
    breakdown_json TEXT NOT NULL,
    PRIMARY KEY (result_id, formula_version),
    CHECK ((points IS NOT NULL AND reason IS NULL) OR
           (points IS NULL AND reason IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS running_athlete_rating (
    athlete_id INTEGER NOT NULL REFERENCES athlete(id) ON DELETE CASCADE,
    formula_version TEXT NOT NULL,
    period_start TEXT NOT NULL,
    period_end TEXT NOT NULL,
    points DOUBLE PRECISION NOT NULL,
    best_points DOUBLE PRECISION NOT NULL,
    starts_count INTEGER NOT NULL,
    rank INTEGER NOT NULL,
    PRIMARY KEY (athlete_id, formula_version, period_start, period_end)
);
CREATE INDEX IF NOT EXISTS ix_rating_score_points ON rating_score(points);
CREATE INDEX IF NOT EXISTS ix_running_athlete_rating_rank
    ON running_athlete_rating(formula_version, period_start, period_end, rank);

CREATE VIEW web_event AS
SELECT id, source_id, name AS title, date_begin::text, date_end::text,
       location AS place, address FROM competition;
CREATE VIEW web_race AS
SELECT id, competition_id AS event_id, name AS name_raw, distance_type AS norm_distance,
       distance_m, distance_km_raw, total_count FROM race;
CREATE VIEW web_result AS
SELECT r.id, r.id AS result_id, r.race_id, l.athlete_id, r.bib, r.full_name_raw, r.gender, r.age, r.birth_year, r.club_raw,
       r.position AS place_abs, r.position_gender AS place_gender, r.chip_time_s, r.gun_time_s,
       r.status, r.duplicate_of FROM result r LEFT JOIN result_athlete l ON l.result_id=r.id;
CREATE VIEW web_athlete_rating AS SELECT * FROM running_athlete_rating;
CREATE VIEW web_rating_score AS SELECT * FROM rating_score;
