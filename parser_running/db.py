"""PostgreSQL: целевая схема парсерного слоя (docs/parser-db-spec.md, раздел 4).

Подключение — переменная DATABASE_URL или файл .env в корне репозитория (образец — .env.example).
Локальная база: `docker compose up -d db`.

Здесь только таблицы, которые заполняет парсер. Вычисляемые слои (athlete, norm, score, rating)
появятся вместе со своими задачами: #9–#13 и спекой сопоставления спортсменов.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = Path(__file__).parent / "data"   # отчёты и кеш ответов площадок (data/raw), в git не попадает

DDL = """
CREATE TABLE IF NOT EXISTS source (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text UNIQUE NOT NULL,
    base_url      text NOT NULL,
    platform      text NOT NULL,              -- rr_api, runc, grom, ...
    parse_method  text,                       -- api, html, browser
    sport_types   text DEFAULT 'run',
    priority      integer DEFAULT 1,          -- дедуп: основным становится старт с меньшим priority
    enabled       boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS competition (
    id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id                 integer NOT NULL REFERENCES source(id),
    external_id               text NOT NULL,
    code                      text,
    name                      text,
    date_begin                date,
    date_end                  date,
    location                  text,
    address                   text,
    sport_type                text,
    source_url                text,
    canonical_competition_id  integer REFERENCES competition(id) ON DELETE SET NULL,   -- дедуп (раздел 7)
    fetched_at                timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_id, external_id)
);
CREATE INDEX IF NOT EXISTS competition_date ON competition(date_begin);
CREATE TABLE IF NOT EXISTS race (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id     integer NOT NULL REFERENCES competition(id),
    external_id        text NOT NULL,
    name               text,
    distance_km_raw    double precision,       -- как в источнике
    distance_m         integer,                -- после нормализации (км, мили, метры, E32)
    distance_type      text,                   -- зачётная дистанция или NULL
    race_type          text,                   -- individual, relay
    place_by           text,                   -- chip, gun: по какому времени площадка дала места
    timing_type        integer,
    is_final_protocol  boolean,
    total_count        integer,
    UNIQUE (competition_id, external_id)
);
-- Сырые ответы площадок. Тело лежит файлом в data/raw (architecture.md 5.1: большие объёмы — вне БД),
-- здесь — что, откуда и для какого объекта получено. object_ref совпадает с issue.object_ref:
-- по задаче из очереди находятся её сохранённые ответы.
CREATE TABLE IF NOT EXISTS raw (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id       integer NOT NULL REFERENCES source(id),
    competition_id  integer REFERENCES competition(id) ON DELETE SET NULL,
    race_id         integer REFERENCES race(id) ON DELETE SET NULL,
    object_ref      text,                     -- 'код_старта' или 'код_старта/дистанция'
    url             text,
    request_key     text NOT NULL,            -- метод + URL + тело
    content_hash    text NOT NULL,            -- sha256 тела: изменение страницы видно по новому хешу
    storage_path    text NOT NULL,            -- путь в data/raw
    size_bytes      integer,
    http_status     integer,
    parse_method    text,
    fetched_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_id, request_key, content_hash)
);
CREATE INDEX IF NOT EXISTS raw_object_ref ON raw(object_ref);
CREATE TABLE IF NOT EXISTS club (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_raw           text UNIQUE NOT NULL,
    name_normalized    text,
    is_sber            boolean NOT NULL,       -- по детектору клуба (SPEC §8.1)
    is_sber_confirmed  boolean                 -- вручную; NULL = не проверяли
);
CREATE TABLE IF NOT EXISTS result (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id                  integer NOT NULL REFERENCES race(id),
    raw_id                   bigint REFERENCES raw(id) ON DELETE SET NULL,
    athlete_id               bigint,           -- NULL до сопоставления (таблица athlete — отдельная спека)
    club_id                  integer REFERENCES club(id),
    external_participant_id  text,
    bib                      text,             -- бывает с буквами
    full_name_raw            text,
    gender                   text,
    age                      integer,
    birth_year               integer,
    birth_date               date,
    country                  text,
    region                   text,
    city                     text,
    club_raw                 text,
    club_source              text,             -- protocol или filter (клуб найден фильтром площадки, E35)
    status                   text,             -- FIN DNF DSQ DNS NC LAP
    position                 integer,
    position_gender          integer,
    age_group                text,
    chip_time_s              double precision,
    gun_time_s               double precision,
    duplicate_of             bigint REFERENCES result(id) ON DELETE SET NULL,   -- та же строка на другой площадке
    match_score              real,
    match_method             text              -- exact, fuzzy, manual
);
CREATE INDEX IF NOT EXISTS result_race ON result(race_id);
CREATE INDEX IF NOT EXISTS result_duplicate_of ON result(duplicate_of);
-- Очередь проблем (spec 4, «issue»): её разбирает агент или человек. Одна проблема = одна строка
-- (fingerprint), повторы увеличивают occurrences. Статусы:
--   new -> agent_working -> proposed -> approved | rejected -> resolved;
--   known — совпало с known_exception (не ошибка); blocked — ждёт внешнего (сеть, заказчик).
CREATE TABLE IF NOT EXISTS issue (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id    integer REFERENCES source(id),
    stage        text NOT NULL,          -- fetch / parse / check / store / dedup / match
    kind         text NOT NULL,          -- fetch_failed / zero_rows / check_failed / geo_block / ...
    object_ref   text,                   -- старт/дистанция
    fingerprint  text NOT NULL UNIQUE,
    details      text,                   -- JSON или текст: что упало
    status       text NOT NULL DEFAULT 'new',
    assignee     text,                   -- agent / human / infra
    journal_ref  text,                   -- номер в ERRORS.md (E1…)
    occurrences  integer NOT NULL DEFAULT 1,
    first_seen   timestamptz NOT NULL DEFAULT now(),
    last_seen    timestamptz NOT NULL DEFAULT now(),
    resolved_at  timestamptz
);
-- То, что выглядит как ошибка, но ею не является (агент не должен это «чинить»).
CREATE TABLE IF NOT EXISTS known_exception (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source       text,                   -- имя площадки; NULL = любая
    kind         text NOT NULL,
    pattern      text NOT NULL,          -- regex по «object_ref + details»
    reason       text NOT NULL,
    journal_ref  text,
    UNIQUE NULLS NOT DISTINCT (source, kind, pattern)
);
-- Попытка агента разобрать задачу из очереди (docs/agent-spec.md §9).
CREATE TABLE IF NOT EXISTS agent_run (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id     integer NOT NULL REFERENCES issue(id),
    model        text,
    tokens_in    integer,
    tokens_out   integer,
    action       text,                   -- patch / known_exception / escalate
    result       text,                   -- proposed / unsafe / bad_patch / not_fixed / regression / error
    patch        text,
    test_report  text,
    started_at   timestamptz NOT NULL DEFAULT now(),
    finished_at  timestamptz
);
"""


def database_url() -> str:
    """DATABASE_URL из окружения, иначе из .env в корне репозитория."""
    if url := os.environ.get("DATABASE_URL"):
        return url
    env = ROOT / ".env"
    if env.exists():
        for line in env.read_text(encoding="utf-8").splitlines():
            if line.startswith("DATABASE_URL="):
                return line.split("=", 1)[1].strip()
    raise RuntimeError("Нет DATABASE_URL: скопируйте .env.example в .env и запустите `docker compose up -d db`")


def connect(url: str | None = None) -> psycopg.Connection:
    con = psycopg.connect(url or database_url())
    con.execute(DDL)
    con.commit()
    return con


def source_id(con: psycopg.Connection, name: str, base_url: str, platform: str,
              parse_method: str | None = None, priority: int = 1) -> int:
    return con.execute("""INSERT INTO source(name, base_url, platform, parse_method, priority)
                          VALUES (%s, %s, %s, %s, %s)
                          ON CONFLICT (name) DO UPDATE SET base_url = excluded.base_url,
                          platform = excluded.platform, parse_method = excluded.parse_method,
                          priority = excluded.priority
                          RETURNING id""", (name, base_url, platform, parse_method, priority)).fetchone()[0]


def report_issue(con: psycopg.Connection, src: int | None, stage: str, kind: str, ref: str,
                 details: dict | str, assignee: str = "agent") -> str:
    """Зарегистрировать проблему в очереди. Возвращает её статус.
    Совпала с known_exception -> 'known'; повтор закрытой проблемы -> снова 'new' (регрессия).
    В fingerprint — имя площадки, а не id: так он одинаков в любой копии базы."""
    text = details if isinstance(details, str) else json.dumps(details, ensure_ascii=False)
    src_name = con.execute("SELECT name FROM source WHERE id = %s", (src,)).fetchone()[0] if src else None
    fp = hashlib.sha1(f"{src_name}|{stage}|{kind}|{ref}".encode()).hexdigest()
    known = next(((jref,) for s, pattern, jref in con.execute(
        "SELECT source, pattern, journal_ref FROM known_exception WHERE kind = %s", (kind,)).fetchall()
        if (s is None or s == src_name) and re.search(pattern, f"{ref} {text}")), None)
    status = "known" if known else "new"
    return con.execute("""INSERT INTO issue(source_id, stage, kind, object_ref, fingerprint, details, status, assignee,
                          journal_ref) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                          ON CONFLICT (fingerprint) DO UPDATE SET occurrences = issue.occurrences + 1,
                          last_seen = now(), details = excluded.details,
                          status = CASE WHEN issue.status = 'resolved' THEN excluded.status ELSE issue.status END,
                          resolved_at = CASE WHEN issue.status = 'resolved' THEN NULL ELSE issue.resolved_at END
                          RETURNING status""",
                       (src, stage, kind, ref, fp, text[:4000], status, None if known else assignee,
                        known[0] if known else None)).fetchone()[0]
